// Short explanations for tooltips, each with an optional link to the matching documentation section.
//
// The texts live in the language files (src/i18n/locales/<lang>/help.json, key "help.<id>");
// this registry only lists the ids and their documentation links. A doc reference is
// "<chapter>#<section>"; chapter and section ids are the same in every language, and a unit
// test checks that every reference exists.

import type { TFunction } from "i18next";

export interface HelpEntry {
  text: string;
  doc?: string;
}

export function docPath(ref: string): string {
  const [chapter, section] = ref.split("#");
  return `/docs/${chapter}${section ? `#${section}` : ""}`;
}

