export type HelpId = keyof typeof HELP_DOCS;

export const HELP_IDS = Object.keys(HELP_DOCS) as HelpId[];

/** The tooltip text in the current language, plus its documentation link. */
/** Placeholder syntax the help texts show literally (i18next would otherwise fill them in). */
const PLACEHOLDERS = { input: "{{input}}", runInput: "{{run.input}}", agentName: "{{Name}}", formName: "{{form.name}}" };

export function helpEntry(t: TFunction, id: HelpId): HelpEntry {
  return { text: t(`help.${id}`, PLACEHOLDERS), doc: HELP_DOCS[id] };
}
